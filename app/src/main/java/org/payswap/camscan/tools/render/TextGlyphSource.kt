package org.payswap.camscan.tools.render

// TextGlyphSource: the built-in 5x7 bitmap font (CAMSCAN-PROD-011
// section 6.1), hand-authored for this repository, covering ASCII 32..126.
// No external font file is used or shipped; the bitmap is encoded as
// compact Int rows (7 rows per glyph, 5 bits per row, bit 4 = leftmost
// column of the glyph cell).
//
// Metrics (documented, binding):
//   - glyph cell is 5 columns x 7 rows;
//   - advance(ch) = 6 px for covered characters (5 px cell + 1 px gap);
//   - advance(ch) = 0 for characters outside 32..126 (they render nothing);
//   - line height = 7 rows + 2 leading rows = 9 px;
//   - measure(text) sums the advances (including the trailing 1 px gap)
//     and reports height = line height for non-empty text, 0 for empty.
//
// The lowercase letters use a documented 7-row layout: baseline row 5,
// x-height rows 2..5, ascenders from row 0, descenders into row 6.

/** One bitmap glyph: [widthPx] x [heightPx] pixels encoded as Int rows. */
class Glyph(
    val widthPx: Int,
    val heightPx: Int,
    rows: IntArray,
) {
    private val rowBits: IntArray = rows.copyOf()

    /** Raw 5-bit row value (bit 4 = leftmost column). */
    fun row(row: Int): Int = rowBits[row]

    /** True when the pixel at ([col], [row]) is set; coordinates 0-based. */
    fun pixel(col: Int, row: Int): Boolean {
        if (col < 0 || col >= widthPx || row < 0 || row >= heightPx) return false
        val bits = rowBits[row]
        return (bits ushr (widthPx - 1 - col)) and 1 == 1
    }

    override fun equals(other: Any?): Boolean {
        if (this === other) return true
        if (other !is Glyph) return false
        return widthPx == other.widthPx && heightPx == other.heightPx &&
            rowBits.contentEquals(other.rowBits)
    }

    override fun hashCode(): Int = 31 * (31 * widthPx + heightPx) + rowBits.contentHashCode()

    override fun toString(): String {
        val sb = StringBuilder("Glyph[")
        sb.append(widthPx).append("x").append(heightPx).append(";rows=")
        for (index in rowBits.indices) {
            if (index > 0) sb.append(",")
            sb.append(Integer.toHexString(rowBits[index]))
        }
        sb.append("]")
        return sb.toString()
    }
}

