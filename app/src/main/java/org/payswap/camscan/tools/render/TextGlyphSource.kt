    /** Glyph for [ch], or null when ch is outside the covered ASCII range. */
    fun glyph(ch: Char): Glyph? {
        val code = ch.code
        if (code < FIRST_CHAR || code > LAST_CHAR) return null
        val rows = IntArray(GLYPH_HEIGHT)
        val base = (code - FIRST_CHAR) * GLYPH_HEIGHT
        for (r in 0 until GLYPH_HEIGHT) {
            rows[r] = FONT_ROWS[base + r]
        }
        return Glyph(GLYPH_WIDTH, GLYPH_HEIGHT, rows)
    }

    /** Horizontal advance for [ch]: 6 px covered, 0 px uncovered. */
    fun advance(ch: Char): Int {
        val code = ch.code
        return if (code >= FIRST_CHAR && code <= LAST_CHAR) ADVANCE_PX else 0
    }

    /** Measured size of [text] under the documented metric contract. */
    fun measure(text: String): Size {
        if (text.isEmpty()) return Size(0, 0)
        var width = 0
        for (index in text.indices) {
            width += advance(text[index])
        }
        return Size(width, lineHeight)
